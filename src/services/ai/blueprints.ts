/**
 * Blueprint library used by the MockAIProvider.
 *
 * Each blueprint is a small "program" that emits a realistic, coherent file
 * set for a domain. This is what makes the demo feel like a real coding agent
 * instead of a lorem-ipsum generator: the produced sites actually render in
 * the live preview, and later edit requests patch these same files.
 *
 * When a real model is connected these blueprints become unnecessary — the
 * provider returns model-authored files in the identical shape.
 */

import type { GeneratedFile } from './AIProvider';

export interface BlueprintContext {
  /** Project/brand name derived from the prompt. */
  brand: string;
  /** Detected domain keyword, e.g. "restaurant". */
  domain: string;
  prompt: string;
}

export interface Blueprint {
  id: string;
  label: string;
  /** Keywords that route a prompt to this blueprint. */
  match: string[];
  entry: string;
  taskTitles: string[];
  /**
   * Generic catch-all. Fallbacks only win when no specific blueprint matches,
   * so "restaurant website" routes to the restaurant blueprint rather than
   * the generic one just because it contains the word "website".
   */
  fallback?: boolean;
  build(ctx: BlueprintContext): GeneratedFile[];
}

