export const BLUEPRINTS: Blueprint[] = [restaurant, landing, dashboard, portfolio];

/**
 * Routes a free-text prompt to the best-matching blueprint.
 *
 * Specific blueprints are scored first; the generic fallback is only used when
 * nothing specific matches. Matching is word-boundary aware so "website" does
 * not spuriously match the keyword "site".
 */
export function selectBlueprint(prompt: string): Blueprint {
  const p = prompt.toLowerCase();

  const score = (bp: Blueprint) => {
    let total = 0;
    for (const kw of bp.match) {
      // Escape regex metacharacters, then require whole-word matches.
      const safe = kw.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      if (new RegExp(`\\b${safe}\\b`).test(p)) total += kw.length;
    }
    return total;
  };

  const specific = BLUEPRINTS.filter((b) => !b.fallback);
  let best: Blueprint | null = null;
  let bestScore = 0;

  for (const bp of specific) {
    const s = score(bp);
    if (s > bestScore) {
      bestScore = s;
      best = bp;
    }
  }

  if (best) return best;

  // Nothing specific matched — use the generic blueprint.
  return BLUEPRINTS.find((b) => b.fallback) ?? portfolio;
}
